import { prepareRuntimeSchema } from "./ipc-schema.mjs";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { compile } from "json-schema-to-typescript";
import Ajv from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const write = process.argv.includes("--write");
if (write) {
  const result = spawnSync("cargo", ["test", "--locked", "--release", "--lib", "--manifest-path", "src-tauri/Cargo.toml", "ipc_contracts::committed_schemas_match_rust"], {
    cwd: root, stdio: "inherit", env: { ...process.env, SIAOVPLAY_UPDATE_CONTRACTS: "1" },
  });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}
const names = ["media-preparation-progress", "subtitle-version-metadata", "ai-model-list", "network-settings", "ai-service-settings", "ai-service-test-result"];
for (const name of names) {
  const schema = JSON.parse(await readFile(resolve(root, `contracts/${name}.schema.json`), "utf8"));
  const examples = schema.examples ?? [];
  const runtimeSchema = prepareRuntimeSchema(schema);
  const title = schema.title;
  if (!/^[A-Z][A-Za-z0-9]*$/.test(title)) throw new Error(`Invalid contract title: ${title}`);
  const types = await compile(runtimeSchema, title, { bannerComment: "/* Generated from Rust IPC schema. Run npm run contracts:generate. */", style: { singleQuote: false } });
  const ajv = new Ajv({ strict: true, allErrors: false, code: { source: true, esm: true, lines: true } });
  const validate = ajv.compile(runtimeSchema);
  for (const example of examples) {
    if (!validate(example)) throw new Error(`Rust serialization disagrees with schema: ${name}`);
  }
  const outputs = {
    [`${name}.ts`]: types,
    [`${name}.validator.mjs`]: "// Generated by Ajv from Rust IPC schema. Do not edit.\n" + standaloneCode(ajv, validate).trimEnd() + "\n",
    [`${name}.validator.d.mts`]: `// Generated. Do not edit.\nimport type { ${title} } from "./${name}";\nexport default function validate(value: unknown): value is ${title};\n`,
  };
  for (const [file, content] of Object.entries(outputs)) {
    const path = resolve(root, "src/generated", file);
    if (write) { await mkdir(dirname(path), { recursive: true }); await writeFile(path, content); }
    else if ((await readFile(path, "utf8")).replaceAll("\r\n", "\n") !== content.replaceAll("\r\n", "\n")) throw new Error(`Stale generated contract: ${file}; run npm run contracts:generate`);
  }
}
console.log(`IPC contracts ${write ? "generated" : "verified"}: ${names.length}`);
